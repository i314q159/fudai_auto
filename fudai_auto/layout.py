"""界面布局（设计坐标）与分辨率自适应换算。

设计基准固定为 1080×2400：
  - 所有 ROI、点击点、关闭位都按这个尺寸写常量；
  - 运行时 ``update_screen(img)`` 根据实际截图刷新 SCALE(x=W/1080, y=H/2400)；
  - 其它模块一律用 ``sc_roi()`` / ``sc_pt()`` 取值，不再直接用像素常量。

这样换手机/换分辨率不用改代码；宽高比略有差异时按 x/y 分别缩放。
"""
from .logbook import log

# ---------------------------------------------------------------------------
# 设计分辨率与缩放系数
# ---------------------------------------------------------------------------
DESIGN_W, DESIGN_H = 1080, 2400

SCALE = {"x": 1.0, "y": 1.0, "w": 0, "h": 0}


def update_screen(img):
    """按截图刷新缩放系数；分辨率没变则直接返回（日志只打印一次）。"""
    h, w = img.shape[:2]
    if w <= 0 or h <= 0 or (w, h) == (SCALE["w"], SCALE["h"]):
        return
    SCALE.update(x=w / DESIGN_W, y=h / DESIGN_H, w=w, h=h)
    log(
        f"屏幕 {w}×{h}，按 {DESIGN_W}×{DESIGN_H} 等比缩放 "
        f"x={SCALE['x']:.2f} y={SCALE['y']:.2f}"
    )


def sx(v):
    """设计像素 -> 实际横向像素。"""
    return v * SCALE["x"]


def sy(v):
    """设计像素 -> 实际纵向像素。"""
    return v * SCALE["y"]


def sc_roi(roi):
    """设计坐标 ROI -> 实际像素 ROI (x0, y0, x1, y1)。"""
    return (
        int(round(roi[0] * SCALE["x"])),
        int(round(roi[1] * SCALE["y"])),
        int(round(roi[2] * SCALE["x"])),
        int(round(roi[3] * SCALE["y"])),
    )


def sc_pt(x, y):
    """设计坐标点 -> 实际像素点，用于 tap / swipe。"""
    return int(round(x * SCALE["x"])), int(round(y * SCALE["y"]))


def crop(img, roi):
    """按 (x0, y0, x1, y1) 裁剪；roi 需是实际像素。"""
    return img[roi[1]:roi[3], roi[0]:roi[2]]


